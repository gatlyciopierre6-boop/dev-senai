-- EX15: FUNCOES DE AGREGACAO -SUM,AVG,MIN,MAX,COUNT
-- COUNT - CONTAR QAUNTIDADE DE REGISTROS
-- SUM - SOMA DE VALORES
-- AVG - MEDIA DE VALORES
-- MIN - MENOR VALOR
-- MAX - MAIOR VALOR

SELECT COUNT(*) AS TOTAL_CLIENTES
FROM CLIENTE;
-- RESULTADO DE QUANTIDADE DE CLIENTES

SELECT AVG(PRECO) AS MEDIA_PRECOS 
FROM PRODUTO;
-- MEDIA DO VALOR DOS PRODUTOS

