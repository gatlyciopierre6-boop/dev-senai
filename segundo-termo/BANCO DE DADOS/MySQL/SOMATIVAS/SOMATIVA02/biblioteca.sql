-- =====================================================================
-- FASE 3 - DQL: CONSULTAS E ANALISE
-- =====================================================================

SELECT TITULO, AUTOR, QUANTIDADE_DISPONIVEL
FROM LIVRO;

SELECT TITULO, AUTOR, QUANTIDADE_DISPONIVEL
FROM LIVRO
WHERE QUANTIDADE_DISPONIVEL > 2
ORDER BY QUANTIDADE_DISPONIVEL DESC;

SELECT ID_LIVRO, TITULO, AUTOR
FROM LIVRO
WHERE TITULO LIKE '%Menina%';

SELECT TITULO, AUTOR, ANO_PUBLICACAO
FROM LIVRO
WHERE ANO_PUBLICACAO BETWEEN 2015 AND 2025
ORDER BY ANO_PUBLICACAO;

SELECT
    COUNT(QUANTIDADE_DISPONIVEL) AS TOTAL_LIVROS,
    SUM(QUANTIDADE_DISPONIVEL)   AS SOMA_EXEMPLARES,
    AVG(QUANTIDADE_DISPONIVEL)   AS MEDIA_EXEMPLARES,
    MIN(QUANTIDADE_DISPONIVEL)   AS MENOR_ESTOQUE,
    MAX(QUANTIDADE_DISPONIVEL)   AS MAIOR_ESTOQUE
FROM LIVRO;

SELECT
    E.ID_EMPRESTIMO,
    U.NOME AS USUARIO,
    L.TITULO AS LIVRO,
    E.DATA_EMPRESTIMO,
    E.STATUS_EMPRESTIMO
FROM EMPRESTIMO E
INNER JOIN USUARIO U ON U.ID_USUARIO = E.ID_USUARIO
INNER JOIN LIVRO L   ON L.ID_LIVRO   = E.ID_LIVRO;

SELECT
    E.ID_EMPRESTIMO,
    U.NOME AS USUARIO,
    L.TITULO AS LIVRO,
    E.DATA_EMPRESTIMO,
    E.DATA_PREVISTA,
    E.STATUS_EMPRESTIMO
FROM EMPRESTIMO E
INNER JOIN USUARIO U ON U.ID_USUARIO = E.ID_USUARIO
INNER JOIN LIVRO L   ON L.ID_LIVRO   = E.ID_LIVRO
WHERE E.STATUS_EMPRESTIMO = 'ABERTO';

SELECT
    U.ID_USUARIO,
    U.NOME,
    COUNT(E.ID_EMPRESTIMO) AS QTD_EMPRESTIMOS
FROM USUARIO U
INNER JOIN EMPRESTIMO E ON E.ID_USUARIO = U.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY QTD_EMPRESTIMOS DESC;

SELECT
    U.ID_USUARIO,
    U.NOME,
    COUNT(E.ID_EMPRESTIMO) AS QTD_EMPRESTIMOS
FROM USUARIO U
LEFT JOIN EMPRESTIMO E ON E.ID_USUARIO = U.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY QTD_EMPRESTIMOS DESC;
