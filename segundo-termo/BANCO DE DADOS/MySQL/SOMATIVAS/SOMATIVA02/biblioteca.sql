CREATE DATABASE IF NOT EXISTS BIBLIOTECA_SOM2_PIERRE;
USE BIBLIOTECA_SOM2_PIERRE;

CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT NOT NULL DEFAULT 0,
    CONSTRAINT CK_LIVRO_QTD CHECK (QUANTIDADE_DISPONIVEL >= 0)
);

CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT CK_EMP_STATUS CHECK (STATUS_EMPRESTIMO IN ('ABERTO', 'DEVOLVIDO', 'ATRASADO')),
    CONSTRAINT FK_EMPRESTIMO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT FK_EMPRESTIMO_LIVRO FOREIGN KEY (ID_LIVRO)
        REFERENCES LIVRO (ID_LIVRO)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE FORMA_PAGAMENTO (
    ID_FORMA_PAGAMENTO INT PRIMARY KEY AUTO_INCREMENT,
    DESCRICAO VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE PAGAMENTO (
    ID_PAGAMENTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_EMPRESTIMO INT NOT NULL,
    VALOR DECIMAL(10,2) NOT NULL,
    DATA_PAGAMENTO DATETIME,
    ID_FORMA_PAGAMENTO INT NOT NULL,
    CONSTRAINT FK_PAGAMENTO_EMPRESTIMO FOREIGN KEY (ID_EMPRESTIMO)
        REFERENCES EMPRESTIMO (ID_EMPRESTIMO),
    CONSTRAINT FK_PAGAMENTO_FORMA FOREIGN KEY (ID_FORMA_PAGAMENTO)
        REFERENCES FORMA_PAGAMENTO (ID_FORMA_PAGAMENTO)
);

ALTER TABLE LIVRO ADD COLUMN EDITORA VARCHAR(100);


