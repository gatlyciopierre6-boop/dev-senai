CREATE DATABASE OFICINA_PIERRE;

USE OFICINA_PIERRE;

CREATE TABLE CLIENTES (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    TELEFONE CHAR(15) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    NOME VARCHAR(60) NOT NULL,
    ENDERECO VARCHAR(100),
    CPF CHAR(14) NOT NULL
);

CREATE TABLE IF NOT EXISTS VEICULOS (
    ID_VEICULO INT AUTO_INCREMENT PRIMARY KEY,
    DESCICAO TEXT(300) NOT NULL,
    PLACA CHAR(8) NOT NULL UNIQUE,
    COR VARCHAR(25) NOT NULL,
    MARCA VARCHAR(25) NOT NULL,
    QUILOMETRAGEM INT
);

CREATE TABLE IF NOT EXISTS MARCAS (
    ID_MARCA INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    PAIS_ORIGEM VARCHAR(30),
    ANO_LANÇAMENTO YEAR,
    MODELO TEXT(500),
    TIPO_COMBUSTIVEL ENUM(`GASOLINA`,`ETANOL`,`DIESEL`) DEFAULT `ETANOL`
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIME
);

CREATE TABLE IF NOT EXISTS MODELOS (
    ID_MODELO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_MODELO VARCHAR(30) NOT NULL,
    TIPO_MODELO ENUM(`SUV`,`COMPACTO`,`SEDAN`) DEFAULT `COMPACTO`,
    ANO_FABRICADO YEAR NOT NULL,
    POTENCIA CHAR(10),
    STATUS_MODELO ENUM(`ATIVO`,`INATIVO`) DEFAULT `ATIVO`,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FUNCIONARIOS (
    ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_FUNCIONARIO VARCHAR(60) NOT NULL,
    CPF_FUNCIONARIO CHAR(15) NOT NULL UNIQUE
    TELEFONE_FUNCIONARIO CHAR
);

CREATE TABLE IF NOT EXISTS SERVIÇOS (
    ID_SERVIÇOS INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    VALOR DECIMAL(10, 2) NOT NULL,
    CATEGORIA VARCHAR(60),
    SERVIÇOS_STATUS VARCHAR(20) NOT NULL DEFAULT 'pendente',
    VALOR VARCHAR(150),
     DESCRICAO VARCHAR(150) NOT NULL,
    id_ordens_servicos INT UNSIGNED,
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
    id_fornecedores INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    razao_social VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    endereco VARCHAR(250)
);
